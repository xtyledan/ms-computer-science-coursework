CREATE TABLE IF NOT EXISTS items (
    item_number INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(128) NOT NULL,
    cost NUMERIC(12, 2) NOT NULL CHECK (cost >= 0),
    retail NUMERIC(12, 2) NOT NULL CHECK (retail >= 0)
);

CREATE TABLE IF NOT EXISTS invoice (
    invoice_number INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_number INTEGER NOT NULL
        REFERENCES company(customer_number),
    representative_id INTEGER NOT NULL
        REFERENCES representative(representative_id),
    date_of_sale DATE NOT NULL
);

CREATE TABLE IF NOT EXISTS line_items (
    line_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    invoice_number INTEGER NOT NULL
        REFERENCES invoice(invoice_number)
        ON DELETE CASCADE,

    item_number INTEGER NOT NULL
        REFERENCES items(item_number),

    qty INTEGER NOT NULL CHECK (qty > 0),

    discount NUMERIC(5, 2) NOT NULL DEFAULT 0
        CHECK (discount >= 0 AND discount <= 100),

    unit_price NUMERIC(12, 2) NOT NULL
        CHECK (unit_price >= 0)
);

CREATE INDEX IF NOT EXISTS idx_invoice_customer
    ON invoice(customer_number);

CREATE INDEX IF NOT EXISTS idx_invoice_representative
    ON invoice(representative_id);

CREATE INDEX IF NOT EXISTS idx_line_items_invoice
    ON line_items(invoice_number);

CREATE INDEX IF NOT EXISTS idx_line_items_item
    ON line_items(item_number);